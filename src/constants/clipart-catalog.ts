export type ClipartCategoryId = (typeof CLIPART_CATEGORIES)[number]['id'];

export type ClipartCatalogEntry = {
  id: string;
  category: ClipartCategoryId;
  label: string;
  /** Motif family used to draw the SVG glyph. */
  motif: string;
};

function pack(
  category: ClipartCategoryId,
  prefix: string,
  motif: string,
  labels: string[],
): ClipartCatalogEntry[] {
  return labels.map((label, index) => ({
    id: `${prefix}-${index + 1}`,
    category,
    label,
    motif: `${motif}:${index}`,
  }));
}

