/**
 * Hand-drawn Indian-market stickers. Every drawing matches its name (the old 640-entry grid reused
 * 16 shapes per family, so labels and art disagreed). 24x24 grid, currentColor, only primitives the
 * clipart parser understands: path, circle, rect, ellipse, line, polygon.
 */

export type IndiaClipartEntry = {
  id: string;
  category: ClipartCategoryId;
  label: string;
  svg: string;
};

/** The ₹ sign. `x`,`y` is its top-left, `s` scales the 12 x 15 design box. */
function rupee(x: number, y: number, s: number, sw = 1.7): string {
  const n = (v: number) => Math.round(v * 100) / 100;
  const X = (v: number) => n(x + v * s);
  const Y = (v: number) => n(y + v * s);
  return (
    p(`M${X(0)} ${Y(0)}H${X(12)}M${X(0)} ${Y(4.6)}H${X(12)}`, false, sw) +
    p(
      `M${X(3)} ${Y(0)}C${X(7)} ${Y(0)} ${X(8.6)} ${Y(1.8)} ${X(8.6)} ${Y(4.3)}S${X(7)} ${Y(8.6)} ${X(3)} ${Y(8.6)}H${X(1)}L${X(9.2)} ${Y(15)}`,
      false,
      sw,
    )
  );
}

const dot = (x: number, y: number, rad = 1) => c(x, y, rad, true);

type Def = [id: string, label: string, body: string];

function pack(category: ClipartCategoryId, defs: Def[]): IndiaClipartEntry[] {
  return defs.map(([id, label, body]) => ({ id: `in-${id}`, category, label, svg: wrap(body) }));
}

