/**
 * Rasterize @twemoji/svg into assets/twemoji, then pack every PNG into ONE file
 * (assets/twemoji-pack/twemoji.bin) plus an offset index in src/lib/emoji/twemoji-modules.ts.
 * EAS Update allows 1000 assets per update, so the PNGs must not be bundled one by one.
 * Skips rasterizing when the stamp matches the installed SVG set; re-packs when the pack is missing.
 */
import { readdir, readFile, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { Resvg } from '@resvg/resvg-js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = path.join(root, 'node_modules/@twemoji/svg');
const outDir = path.join(root, 'assets/twemoji');
const modulesFile = path.join(root, 'src/lib/emoji/twemoji-modules.ts');
const stampFile = path.join(outDir, '.generated');
const packDir = path.join(root, 'assets/twemoji-pack');
const packFile = path.join(packDir, 'twemoji.bin');
const SIZE = 128;

async function svgNames() {
  const names = (await readdir(svgDir)).filter((name) => name.endsWith('.svg')).sort();
  return names;
}

async function renderOne(name) {
  const id = name.slice(0, -4);
  const svg = await readFile(path.join(svgDir, name));
  const png = new Resvg(svg, {
    fitTo: { mode: 'width', value: SIZE },
    background: 'rgba(0,0,0,0)',
    font: { loadSystemFonts: false },
  })
    .render()
    .asPng();
  await writeFile(path.join(outDir, `${id}.png`), png);
  return id;
}

async function pool(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  async function run() {
    while (next < items.length) {
      const index = next;
      next += 1;
      results[index] = await worker(items[index]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, () => run()));
  return results;
}

async function packAll() {
  const ids = (await readdir(outDir))
    .filter((name) => name.endsWith('.png'))
    .map((name) => name.slice(0, -4))
    .sort();
  const chunks = [];
  const index = [];
  let offset = 0;
  for (const id of ids) {
    const png = await readFile(path.join(outDir, `${id}.png`));
    index.push(`  '${id}': [${offset}, ${png.length}],`);
    chunks.push(png);
    offset += png.length;
  }
  await mkdir(packDir, { recursive: true });
  await writeFile(packFile, Buffer.concat(chunks));
  const source = `/* Generated by scripts/generate-twemoji-assets.mjs. Do not edit. */
/* eslint-disable */
// @ts-nocheck
/** One bundled asset holding every Twemoji PNG back to back. */
export const TWEMOJI_PACK: number = require('../../../assets/twemoji-pack/twemoji.bin');
/** file id -> [byte offset, byte length] inside TWEMOJI_PACK. */
export const TWEMOJI_INDEX: Record<string, [number, number]> = {
${index.join('\n')}
};
`;
  await writeFile(modulesFile, source);
  console.log(`[twemoji] packed ${ids.length} pngs into ${path.relative(root, packFile)} (${offset} bytes)`);
}

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

const names = await svgNames();
const stamp = `${names.length}\n`;
let current = '';
try {
  current = await readFile(stampFile, 'utf8');
} catch {
  current = '';
}
if (current === stamp && !process.argv.includes('--force')) {
  if (!(await exists(packFile))) await packAll();
  else console.log(`[twemoji] ${names.length} assets already generated`);
  process.exit(0);
}

await mkdir(outDir, { recursive: true });
console.log(`[twemoji] rasterizing ${names.length} SVGs at ${SIZE}px`);
await pool(names, 8, renderOne);
await packAll();
await writeFile(stampFile, stamp);
