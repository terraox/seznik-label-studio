/**
 * Rasterize @twemoji/svg into assets/twemoji and a Metro require map.
 * Skips when the stamp matches the installed SVG set.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { Resvg } from '@resvg/resvg-js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = path.join(root, 'node_modules/@twemoji/svg');
const outDir = path.join(root, 'assets/twemoji');
const modulesFile = path.join(root, 'src/lib/emoji/twemoji-modules.ts');
const stampFile = path.join(outDir, '.generated');
const SIZE = 128;

async function svgNames() {
  const names = (await readdir(svgDir)).filter((name) => name.endsWith('.svg')).sort();
  return names;
}

async function renderOne(name) {
  const id = name.slice(0, -4);
  const svg = await readFile(path.join(svgDir, name));
  const png = new Resvg(svg, {
    fitTo: { mode: 'width', value: SIZE },
    background: 'rgba(0,0,0,0)',
    font: { loadSystemFonts: false },
  })
    .render()
    .asPng();
  await writeFile(path.join(outDir, `${id}.png`), png);
  return id;
}

async function pool(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  async function run() {
    while (next < items.length) {
      const index = next;
      next += 1;
      results[index] = await worker(items[index]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, () => run()));
  return results;
}

const names = await svgNames();
const stamp = `${names.length}\n`;
let current = '';
try {
  current = await readFile(stampFile, 'utf8');
} catch {
  current = '';
}
if (current === stamp && !process.argv.includes('--force')) {
  console.log(`[twemoji] ${names.length} assets already generated`);
  process.exit(0);
}

await mkdir(outDir, { recursive: true });
await mkdir(path.dirname(modulesFile), { recursive: true });
console.log(`[twemoji] rasterizing ${names.length} SVGs at ${SIZE}px`);
const ids = await pool(names, 8, renderOne);
const lines = ids
  .filter(Boolean)
  .map((id) => `  '${id}': require('../../../assets/twemoji/${id}.png'),`);
const source = `/* Generated by scripts/generate-twemoji-assets.mjs. Do not edit. */
/* eslint-disable */
// @ts-nocheck
export const TWEMOJI_MODULES: Record<string, number> = {
${lines.join('\n')}
};
`;
await writeFile(modulesFile, source);
await writeFile(stampFile, stamp);
console.log(`[twemoji] wrote ${ids.length} pngs and ${path.relative(root, modulesFile)}`);
